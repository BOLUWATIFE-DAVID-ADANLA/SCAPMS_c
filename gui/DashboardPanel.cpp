QLabel* DashboardPanel::makeCard(const QString& title, const QString& colour, const QString& tooltip, QWidget*& card) {
    auto* frame = new QFrame;
    frame->setObjectName("statCard");
    frame->setStyleSheet(QString("#statCard { border-left: 5px solid %1; }").arg(colour));
    frame->setToolTip(tooltip);
    auto* titleLabel = new QLabel(title);
    titleLabel->setObjectName("cardTitle");
    auto* value = new QLabel("0");
    value->setObjectName("cardValue");
    value->setStyleSheet(QString("color: %1;").arg(colour));
    auto* layout = new QVBoxLayout(frame);
    layout->addWidget(titleLabel);
    layout->addWidget(value);
    card = frame;
    return value;
}

DashboardPanel::DashboardPanel(controller::ClinicManager& manager, QWidget* parent) : BasePanel(manager, parent) {
    // QGridLayout: 2 rows x 3 columns of statistic cards that resize evenly.
    auto* cards = new QGridLayout;
    cards->setSpacing(12);
    QWidget* c = nullptr;
    totalValue_ = makeCard("Registered Patients", "#3A5CCC", "All patients in the system.", c);
    cards->addWidget(c, 0, 0);
    emergencyValue_ = makeCard("Emergency Patients", "#D93F45", "Patients flagged as Emergency (high priority).", c);
    cards->addWidget(c, 0, 1);
    queueValue_ = makeCard("Waiting in Queue", "#7A4CC2", "Patients waiting for consultation.", c);
    cards->addWidget(c, 0, 2);
    todayValue_ = makeCard("Appointments Today", "#0E7C86", "All appointments dated today.", c);
    cards->addWidget(c, 1, 0);
    pendingValue_ = makeCard("Pending Today", "#C77C02", "Today's appointments not yet completed.", c);
    cards->addWidget(c, 1, 1);
    completedValue_ = makeCard("Completed Today", "#2A9461", "Today's appointments already attended.", c);
    cards->addWidget(c, 1, 2);

    upcoming_ = new QTableWidget;
    setupTable(upcoming_, {"Time", "Patient", "Category", "Reason", "Status"});
    upcoming_->setItemDelegateForColumn(4, BadgeDelegate::forStatus(upcoming_));
    upcoming_->setColumnWidth(0, 60);
    upcoming_->setColumnWidth(1, 160);
    upcoming_->setColumnWidth(2, 90);
    upcoming_->setColumnWidth(3, 180);
    upcoming_->setSelectionMode(QAbstractItemView::NoSelection);
    auto* upcomingBox = new QGroupBox("Today's Schedule");
    auto* ul = new QVBoxLayout(upcomingBox);
    ul->addWidget(upcoming_);

    triage_ = new QListWidget;
    triage_->setWordWrap(true);
    triage_->setToolTip("Generated by calling virtual functions through PatientRecord pointers (runtime polymorphism).");
    auto* triageBox = new QGroupBox("Triage Overview (by priority)");
    auto* tl = new QVBoxLayout(triageBox);
    tl->addWidget(triage_);

    auto* lower = new QHBoxLayout;
    lower->addWidget(upcomingBox, 1);
    lower->addWidget(triageBox, 1);

    refreshedLabel_ = new QLabel;
    refreshedLabel_->setObjectName("mutedLabel");

    auto* root = new QVBoxLayout(this);
    root->addLayout(cards);
    root->addLayout(lower, 1);
    root->addWidget(refreshedLabel_);
}

void DashboardPanel::refresh() {
    const auto& db = manager_.database();
    const std::string today = utils::DateUtils::today();
    const auto summary = controller::ReportGenerator::dailySummary(db, today);
    const auto categories = controller::ReportGenerator::categoryDistribution(db);

    totalValue_->setText(QString::number(db.size()));
    emergencyValue_->setText(QString::number(categories[1].count));
    queueValue_->setText(QString::number(db.queueSize()));
    todayValue_->setText(QString::number(summary.total));
    pendingValue_->setText(QString::number(summary.pending));
    completedValue_->setText(QString::number(summary.completed));

    const auto todays = manager_.appointments().onDate(today);
    upcoming_->setRowCount(static_cast<int>(todays.size()));
    for (int r = 0; r < static_cast<int>(todays.size()); ++r) {
        const auto& v = todays[r];
        QTableWidgetItem* items[] = {makeItem(q(v.appointment.getTime())), makeItem(q(v.patientName)),
                                     makeItem(q(v.category)), makeItem(q(v.appointment.getReason())),
                                     makeItem(q(model::statusToString(v.appointment.getStatus())))};
        for (int col = 0; col < 5; ++col) upcoming_->setItem(r, col, items[col]);
        if (v.category == "Emergency") items[2]->setForeground(categoryColor(model::PatientCategory::Emergency));
    }

    triage_->clear();
    const auto lines = manager_.triageOverview();
    for (std::size_t i = 0; i < lines.size(); ++i) {
        auto* item = new QListWidgetItem(q(lines[i]));
        const QString text = item->text();
        if (text.contains("Emergency:")) item->setForeground(categoryColor(model::PatientCategory::Emergency));
        else if (text.contains("Follow-Up:")) item->setForeground(categoryColor(model::PatientCategory::FollowUp));
        triage_->addItem(item);
    }
    if (lines.empty()) triage_->addItem("No patients registered.");

    refreshedLabel_->setText("Last refreshed " + QDateTime::currentDateTime().toString("HH:mm:ss") +
                             "  (auto-refresh every 30 seconds)");
}

